-- Rôles au moindre privilège et warehouse dédié aux traitements.
USE ROLE ACCOUNTADMIN;

-- Warehouse dédié aux traitements : coûts isolés, arrêt après 60 s
CREATE WAREHOUSE IF NOT EXISTS ETL_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS ADF_LOADER;
CREATE ROLE IF NOT EXISTS AIRFLOW_ROLE;
GRANT ROLE ADF_LOADER   TO ROLE SYSADMIN;
GRANT ROLE AIRFLOW_ROLE TO ROLE SYSADMIN;

-- Commun
GRANT USAGE ON WAREHOUSE ETL_WH TO ROLE ADF_LOADER;
GRANT USAGE ON WAREHOUSE ETL_WH TO ROLE AIRFLOW_ROLE;
GRANT USAGE ON DATABASE RETAIL  TO ROLE ADF_LOADER;
GRANT USAGE ON DATABASE RETAIL  TO ROLE AIRFLOW_ROLE;

-- ADF : écrit uniquement dans RAW_ADF
GRANT USAGE ON SCHEMA RETAIL.RAW_ADF TO ROLE ADF_LOADER;
GRANT SELECT, INSERT, TRUNCATE ON ALL TABLES IN SCHEMA RETAIL.RAW_ADF TO ROLE ADF_LOADER;

-- Airflow : stage + RAW_AIRFLOW
GRANT USAGE ON SCHEMA RETAIL.LANDING TO ROLE AIRFLOW_ROLE;
GRANT USAGE ON STAGE RETAIL.LANDING.AZURE_LANDING TO ROLE AIRFLOW_ROLE;
GRANT USAGE ON FILE FORMAT RETAIL.LANDING.CSV_HEADER TO ROLE AIRFLOW_ROLE;
GRANT USAGE ON SCHEMA RETAIL.RAW_AIRFLOW TO ROLE AIRFLOW_ROLE;
GRANT SELECT, INSERT, TRUNCATE ON ALL TABLES IN SCHEMA RETAIL.RAW_AIRFLOW TO ROLE AIRFLOW_ROLE;

-- Airflow : lecture de RAW_ADF pour comparer les deux chargements
GRANT USAGE ON SCHEMA RETAIL.RAW_ADF TO ROLE AIRFLOW_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL.RAW_ADF TO ROLE AIRFLOW_ROLE;

-- dbt (lancé par Airflow) crée ses propres schémas : STAGING, MARTS
GRANT CREATE SCHEMA ON DATABASE RETAIL TO ROLE AIRFLOW_ROLE;

SHOW GRANTS TO ROLE AIRFLOW_ROLE;

-- Ajouts découverts pendant la mise en place du pipeline ADF (copie directe vers Snowflake) :
-- ADF utilise la storage integration et crée un stage temporaire (adf_stage_import_<guid>)
-- dans le schéma cible avant chaque COPY INTO.
GRANT USAGE ON INTEGRATION AZURE_LANDING_INT TO ROLE ADF_LOADER;
GRANT CREATE STAGE ON SCHEMA RETAIL.RAW_ADF TO ROLE ADF_LOADER;
GRANT CREATE FILE FORMAT ON SCHEMA RETAIL.RAW_ADF TO ROLE ADF_LOADER;

-- Ajout pour le DAG Airflow : rechargement idempotent d'un fichier
-- (DELETE des lignes du fichier puis COPY INTO, dans une même transaction).
GRANT DELETE ON ALL TABLES IN SCHEMA RETAIL.RAW_AIRFLOW TO ROLE AIRFLOW_ROLE;
